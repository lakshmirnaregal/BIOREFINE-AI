def dashboard(bagasse, moisture, start_temp, start_ph,
              start_pressure, scenario):

    rng = np.random.default_rng()

    # ---------------- SIMULATE SENSOR READINGS ----------------

    n = 60
    times = np.arange(1, n + 1)

    temperatures = []
    ph_values = []
    pressures = []

    temp = float(start_temp)
    ph = float(start_ph)
    pressure = float(start_pressure)

    for t in times:

        temp += rng.normal(0, 0.16)
        ph += rng.normal(0, 0.012)
        pressure += rng.normal(0, 0.006)

        # Introduce disturbances for demonstration.
        if scenario == "Temperature increase" and 12 <= t <= 40:
            temp += 0.22

        elif scenario == "pH disturbance" and 12 <= t <= 40:
            ph += 0.045

        elif scenario == "Pressure increase" and 12 <= t <= 40:
            pressure += 0.025

        temp = float(np.clip(temp, 10, 100))
        ph = float(np.clip(ph, 0, 14))
        pressure = float(np.clip(pressure, 0, 5))

        temperatures.append(temp)
        ph_values.append(ph)
        pressures.append(pressure)

    df = pd.DataFrame({
        "Time (s)": times,
        "Temperature (°C)": temperatures,
        "pH": ph_values,
        "Pressure (bar gauge)": pressures
    })

    peak_temp = max(temperatures)
    low_ph = min(ph_values)
    high_ph = max(ph_values)
    peak_pressure = max(pressures)

    # ---------------- ALERT DETECTION ----------------
    # These are demonstration thresholds, not safety limits.

    alerts = []

    if bagasse > 10000:
        alerts.append((
            "CRITICAL",
            "Excessive bagasse input",
            f"{bagasse:,.0f} kg exceeds the demo limit of 10,000 kg."
        ))

    if peak_temp > 40:
        alerts.append((
            "CRITICAL",
            "High temperature",
            f"Peak simulated temperature: {peak_temp:.2f} °C."
        ))
    elif peak_temp > 38:
        alerts.append((
            "WARNING",
            "Temperature rising",
            f"Peak simulated temperature: {peak_temp:.2f} °C."
        ))

    if low_ph < 4.5 or high_ph > 5.5:
        alerts.append((
            "WARNING",
            "pH deviation",
            f"Simulated pH range: {low_ph:.2f}–{high_ph:.2f}."
        ))

    if peak_pressure > 0.5:
        alerts.append((
            "CRITICAL",
            "High pressure",
            f"Peak simulated pressure: {peak_pressure:.3f} bar gauge."
        ))

    if not alerts:
        alerts.append((
            "NORMAL",
            "Parameters within demo limits",
            "No configured threshold was exceeded."
        ))

    critical = any(a[0] == "CRITICAL" for a in alerts)
    warning = any(a[0] == "WARNING" for a in alerts)

    if critical:
        status = "CRITICAL"
        color = "#ff647c"
    elif warning:
        status = "WARNING"
        color = "#ffc857"
    else:
        status = "NORMAL"
        color = "#38e7bd"

    # ---------------- DIGITAL FERMENTER ----------------

    tank_html = f"""
    <div class="panel" style="text-align:center">
      <h2>🧪 DIGITAL TWIN FERMENTER</h2>
      <svg viewBox="0 0 340 350" width="100%"
           style="max-height:360px"
           xmlns="http://www.w3.org/2000/svg">
        <defs>
          <linearGradient id="steel" x1="0" x2="1">
            <stop offset="0%" stop-color="#17314b"/>
            <stop offset="50%" stop-color="#a6c9df"/>
            <stop offset="100%" stop-color="#17314b"/>
          </linearGradient>
          <linearGradient id="liquid" x1="0" x2="0" y1="0" y2="1">
            <stop offset="0%" stop-color="#29e0ff"/>
            <stop offset="100%" stop-color="#0864bc"/>
          </linearGradient>
          <clipPath id="vessel">
            <rect x="73" y="85" width="194" height="205" rx="30"/>
          </clipPath>
        </defs>
        <rect x="135" y="20" width="70" height="33" rx="7"
              fill="url(#steel)" stroke="#93e7ff" stroke-width="2"/>
        <path d="M150 53 V76 M190 53 V76"
              stroke="#9bcee8" stroke-width="7"/>
        <rect x="65" y="72" width="210" height="235" rx="38"
              fill="url(#steel)" stroke="{color}" stroke-width="4"/>
        <g clip-path="url(#vessel)">
          <rect x="73" y="150" width="194" height="145"
                fill="url(#liquid)"/>
          <path d="M73 150 Q97 138 121 150 T169 150 T217 150 T267 150"
                fill="none" stroke="#b8f9ff" stroke-width="3"/>
          <circle cx="110" cy="205" r="5" fill="#d7ffff"/>
          <circle cx="220" cy="240" r="6" fill="#d7ffff"/>
          <circle cx="157" cy="267" r="4" fill="#d7ffff"/>
        </g>
        <line x1="170" y1="52" x2="170" y2="260"
              stroke="#e5f7ff" stroke-width="5"/>
        <path d="M125 181 H215 M135 169 L125 191 M205 169 L215 191"
              stroke="#e5f7ff" stroke-width="6" fill="none"/>
        <path d="M95 301 L84 340 M245 301 L256 340"
              stroke="#86b3d1" stroke-width="11"/>
        <text x="170" y="345" fill="#eaf6ff"
              text-anchor="middle" font-size="13">FERMENTER BR-101</text>
      </svg>
      <h2 style="color:{color}">● {status}</h2>
      <p>
        Temperature: {temperatures[-1]:.2f} °C<br>
        pH: {ph_values[-1]:.2f}<br>
        Pressure: {pressures[-1]:.3f} bar(g)
      </p>
    </div>
    """

    # ---------------- ALERT PANEL ----------------

    alert_html = '<div class="panel"><h2>🚨 AI ALERT CENTER</h2>'

    for severity, title, description in alerts:
        item_color = (
            "#ff647c" if severity == "CRITICAL"
            else "#ffc857" if severity == "WARNING"
            else "#38e7bd"
        )
        icon = (
            "🔴" if severity == "CRITICAL"
            else "🟠" if severity == "WARNING"
            else "🟢"
        )

        alert_html += f"""
        <div class="alert" style="border-color:{item_color}">
          <b style="color:{item_color}">{icon} {severity}: {title}</b>
          <p class="muted">{description}</p>
        </div>
        """

    alert_html += """
    <p class="muted">
      The alert engine uses configured rules, not a trained AI model.
    </p></div>
    """

    # ---------------- KPI CARDS ----------------

    kpis_html = f"""
    <div class="kpis">
      <div class="kpi">
        <div class="kpi-label">🌡️ PEAK TEMPERATURE</div>
        <div class="kpi-value">{peak_temp:.2f} °C</div>
      </div>
      <div class="kpi">
        <div class="kpi-label">🧪 ENDING pH</div>
        <div class="kpi-value">{ph_values[-1]:.2f}</div>
      </div>
      <div class="kpi">
        <div class="kpi-label">💨 PEAK PRESSURE</div>
        <div class="kpi-value">{peak_pressure:.3f} bar</div>
      </div>
      <div class="kpi">
        <div class="kpi-label">💧 MOISTURE</div>
        <div class="kpi-value">{moisture}%</div>
      </div>
    </div>
    """

    # ---------------- GRAPHS ----------------

    def style_plot(fig, title, ylabel):
        fig.update_layout(
            title=title,
            xaxis_title="Simulation time (seconds)",
            yaxis_title=ylabel,
            height=330,
            template="plotly_dark",
            paper_bgcolor="#10243a",
            plot_bgcolor="#10243a",
            font=dict(color="#eaf4ff"),
            margin=dict(l=40, r=20, t=55, b=40)
        )
        fig.update_xaxes(gridcolor="#294159")
        fig.update_yaxes(gridcolor="#294159")
        return fig

    fig_temp = go.Figure()
    fig_temp.add_trace(go.Scatter(
        x=times, y=temperatures,
        mode="lines",
        line=dict(color="#42d9ff", width=3),
        name="Temperature"
    ))
    fig_temp.add_hline(
        y=40, line_dash="dash", line_color="#ff647c",
        annotation_text="Demo alert limit"
    )
    fig_temp = style_plot(
        fig_temp, "🌡️ Temperature Trend", "Temperature (°C)"
    )

    fig_ph = go.Figure()
    fig_ph.add_trace(go.Scatter(
        x=times, y=ph_values,
        mode="lines",
        line=dict(color="#a99aff", width=3),
        name="pH"
    ))
    fig_ph.add_hline(y=4.5, line_dash="dash", line_color="#ffc857")
    fig_ph.add_hline(y=5.5, line_dash="dash", line_color="#ffc857")
    fig_ph = style_plot(fig_ph, "🧪 pH Trend", "pH")

    fig_pressure = go.Figure()
    fig_pressure.add_trace(go.Scatter(
        x=times, y=pressures,
        mode="lines",
        line=dict(color="#38e7bd", width=3),
        name="Pressure"
    ))
    fig_pressure.add_hline(
        y=0.5, line_dash="dash", line_color="#ff647c",
        annotation_text="Demo threshold"
    )
    fig_pressure = style_plot(
        fig_pressure, "💨 Pressure Trend", "Pressure (bar gauge)"
    )

    # ---------------- THREE PRODUCT OUTPUTS ----------------

    # Simplified assumptions for demonstration only.
    dry_bagasse = bagasse * (1 - moisture / 100)

    ethanol_kg = dry_bagasse * 0.20
    ethanol_litres = ethanol_kg / 0.789
    biogas_m3 = dry_bagasse * 0.35
    biofertilizer_kg = dry_bagasse * 0.30

    products_html = f"""
    <div class="product-grid">
      <div class="product">
        <h3>🍶 Bioethanol</h3>
        <div class="product-value">{ethanol_litres:,.2f} L</div>
        <p>Estimated mass: {ethanol_kg:,.2f} kg</p>
        <div class="muted">Illustrative conversion factor</div>
      </div>
      <div class="product">
        <h3>♻️ Biogas</h3>
        <div class="product-value">{biogas_m3:,.2f} m³</div>
        <p>Estimated gas volume</p>
        <div class="muted">Illustrative conversion factor</div>
      </div>
      <div class="product">
        <h3>🌾 Biofertilizer</h3>
        <div class="product-value">{biofertilizer_kg:,.2f} kg</div>
        <p>Potential product estimate</p>
        <div class="muted">Illustrative conversion factor</div>
      </div>
    </div>
    <div class="panel" style="margin-top:12px">
      <h3>Feedstock Summary</h3>
      Wet bagasse: {bagasse:,.2f} kg<br>
      Moisture: {moisture}%<br>
      Estimated dry matter: {dry_bagasse:,.2f} kg
    </div>
    <p class="muted">
      Estimates use assumed factors, not experimental yield data.
      The three pathways are not a validated combined mass balance.
    </p>
    """

    # ---------------- PROCESS TABLE AND CSV ----------------

    df.insert(1, "Bagasse input (kg)", bagasse)
    df.insert(2, "Moisture (%)", moisture)
    df["Status"] = np.where(
        (df["Temperature (°C)"] > 40)
        | (df["Pressure (bar gauge)"] > 0.5),
        "CRITICAL",
        np.where(
            (df["Temperature (°C)"] > 38)
            | (df["pH"] < 4.5)
            | (df["pH"] > 5.5),
            "WARNING",
            "NORMAL"
        )
    )

    temp_file = tempfile.NamedTemporaryFile(
        suffix=".csv", delete=False
    )
    temp_file.close()
    df.to_csv(temp_file.name, index=False)

    return (
        kpis_html,
        tank_html,
        alert_html,
        fig_temp,
        fig_ph,
        fig_pressure,
        products_html,
        df.tail(15),
        temp_file.name
    )


